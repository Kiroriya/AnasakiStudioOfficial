package api

import (
	"errors"
	"net/http"

	"github.com/anasaki/studio/backend/internal/auth"
	"github.com/anasaki/studio/backend/internal/sitecode"
)

// Site Code phase 5: endpoints for tools (the anasaki-code CLI, editors):
// the draft as a hash tree and an atomic multi-file sync.

func (a *API) codePhase5Routes(c func(pattern, cap string, fn http.HandlerFunc)) {
	const p = "/api/v1/code"
	c("GET "+p+"/tree", auth.CapViewScripts, a.codeTree)
	c("POST "+p+"/sync", auth.CapEditScripts, a.codeSync)
}

type codeTreeOut struct {
	Files        []sitecode.TreeFile `json:"files"`
	LiveVersion  *int64              `json:"liveVersion"`
	DraftChanged bool                `json:"draftChanged"`
}

func (a *API) treeOut() (*codeTreeOut, error) {
	files, err := a.code.DB.Tree()
	if err != nil {
		return nil, err
	}
	st, err := a.code.StatusOf("")
	if err != nil {
		return nil, err
	}
	return &codeTreeOut{Files: files, LiveVersion: st.LiveVersion, DraftChanged: st.DraftChanged}, nil
}

// GET /api/v1/code/tree → {files:[{path, sha256, size, updatedAt}], liveVersion, draftChanged}
func (a *API) codeTree(w http.ResponseWriter, r *http.Request) {
	out, err := a.treeOut()
	if err != nil {
		serverErr(w, err)
		return
	}
	writeJSON(w, http.StatusOK, out)
}

// POST /api/v1/code/sync {put:[{path, content, baseSha256?}], delete:[{path, baseSha256?}], dryRun?}
// → {files, liveVersion, draftChanged, ok, problems, warnings, skipped, written, deleted, dryRun};
// 409 {error, conflicts:[{path, serverSha256}]} with nothing applied.
func (a *API) codeSync(w http.ResponseWriter, r *http.Request) {
	var in struct {
		Put    []sitecode.SyncPut    `json:"put"`
		Delete []sitecode.SyncDelete `json:"delete"`
		DryRun bool                  `json:"dryRun"`
	}
	if !readJSON(w, r, &in) {
		return
	}
	// anasaki.d.ts at the root is generated by the server (GET /types): never stored
	skipped := []string{}
	put := in.Put[:0:0]
	for _, p := range in.Put {
		if p.Path == sitecode.TypesFile {
			skipped = append(skipped, p.Path)
			continue
		}
		put = append(put, p)
	}
	del := in.Delete[:0:0]
	for _, d := range in.Delete {
		if d.Path == sitecode.TypesFile {
			skipped = append(skipped, d.Path)
			continue
		}
		del = append(del, d)
	}
	a.codeMu.Lock()
	plan, err := a.code.DB.Sync(put, del, in.DryRun, auth.From(r).ID)
	a.codeMu.Unlock()
	var conflicts *sitecode.SyncConflicts
	if errors.As(err, &conflicts) {
		writeJSON(w, http.StatusConflict, map[string]any{
			"error":     "ไฟล์บนเซิร์ฟเวอร์เปลี่ยนไปหลังจากที่คุณดึงมา — ดึง (pull) ใหม่ก่อน / files changed on the server since your last pull",
			"conflicts": conflicts.List,
		})
		return
	}
	if err != nil {
		codeErr(w, err)
		return
	}
	written, deleted := append([]string{}, sitecode.Sorted(plan.Write)...), append([]string{}, plan.Remove...)
	if !in.DryRun && (len(written) > 0 || len(deleted) > 0) {
		a.codeAudit(r, "sync", map[string]any{"written": written, "deleted": deleted})
	}
	// the build check of the (resulting) draft, so `watch` can print problems
	build, err := a.code.BuildFiles(plan.Result)
	if err != nil {
		serverErr(w, err)
		return
	}
	tree, err := a.treeOut()
	if err != nil {
		serverErr(w, err)
		return
	}
	if in.DryRun { // the tree as it would be (unchanged files keep their time)
		at := map[string]sitecode.TreeFile{}
		for _, f := range tree.Files {
			at[f.Path] = f
		}
		files := []sitecode.TreeFile{}
		for _, p := range sitecode.Sorted(plan.Result) {
			c := plan.Result[p]
			f := sitecode.TreeFile{Path: p, SHA256: sitecode.ContentHash(c), Size: len(c)}
			if old, ok := at[p]; ok && old.SHA256 == f.SHA256 {
				f.UpdatedAt = old.UpdatedAt
			}
			files = append(files, f)
		}
		tree.Files = files
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"files":        tree.Files,
		"liveVersion":  tree.LiveVersion,
		"draftChanged": tree.DraftChanged,
		"ok":           build.OK,
		"problems":     build.Errors,
		"warnings":     build.Warnings,
		"skipped":      skipped,
		"written":      written,
		"deleted":      deleted,
		"dryRun":       in.DryRun,
	})
}
